/**
 * Print fresh values for every key env var (FREE-TIER.md §11 step 8).
 *
 *   pnpm exec tsx packages/crypto/scripts/gen-keys.ts          # production/preview values
 *   pnpm exec tsx packages/crypto/scripts/gen-keys.ts --dev    # + local dev OIDC issuer
 *   pnpm exec tsx packages/crypto/scripts/gen-keys.ts --kid v2 # next rotation kid
 *
 * Output is dotenv-style on stdout. Paste each value into the right Vercel project as a
 * **Secret** env var (never commit it): IMG_PUBKEYS goes to edf-view, TOKEN_KEKS/TOKEN_KEK_ACTIVE
 * to edf-keys only, everything else to edf-app. Generate separate values per environment.
 * For rotation, merge the new kid into the existing JSON object (keep old kids until every
 * value sealed/signed with them has expired or been re-wrapped).
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { KID_RE } from "../src/keyring";

const args = process.argv.slice(2);
const kidIdx = args.indexOf("--kid");
const kid = kidIdx >= 0 ? (args[kidIdx + 1] ?? "") : "v1";
if (!KID_RE.test(kid)) {
  console.error("invalid --kid (expected [A-Za-z0-9_-]{1,32})");
  process.exit(1);
}
const dev = args.includes("--dev");

const secret32 = (): string => randomBytes(32).toString("base64");
const ring = (): string => JSON.stringify({ [kid]: secret32() });
const quote = (v: string): string => `'${v}'`;

const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const imgPriv = privateKey.export({ format: "der", type: "pkcs8" }).toString("base64");
const imgPub = publicKey.export({ format: "der", type: "spki" }).toString("base64");
const kidNumber = /^\D*(\d+)$/.exec(kid)?.[1] ?? "1";

const lines: Array<[string, string, string]> = [
  ["edf-app", "VIEW_KEYS", ring()],
  ["edf-app", "OUT_KEYS", ring()],
  ["edf-app", "STATE_KEYS", ring()],
  ["edf-app", "INVITE_KEYS", ring()],
  ["edf-app", "ACCESS_TOKEN_KEYS", ring()],
  ["edf-app", "IMG_SIGNING_KEYS", JSON.stringify({ [kid]: imgPriv })],
  ["edf-app", "CRON_SECRET", randomBytes(32).toString("base64url")],
  // Better Auth 1.7 format: "<version>:<secret>[,<older version>:<secret>…]", current first.
  ["edf-app", "BETTER_AUTH_SECRETS", `${kidNumber}:${randomBytes(32).toString("base64url")}`],
  ["edf-view", "IMG_PUBKEYS", JSON.stringify({ [kid]: imgPub })],
  ["edf-keys", "TOKEN_KEKS", ring()],
  ["edf-keys", "TOKEN_KEK_ACTIVE", kid],
];

const out: string[] = [
  "# Generated by packages/crypto/scripts/gen-keys.ts — SECRET VALUES, do not commit or paste in chat.",
];
let project = "";
for (const [p, name, value] of lines) {
  if (p !== project) {
    out.push("", `# ── ${p} ──`);
    project = p;
  }
  out.push(`${name}=${quote(value)}`);
}

if (dev) {
  if (
    process.env.NODE_ENV === "production" ||
    process.env.VERCEL_ENV ||
    process.env.VERCEL === "1"
  ) {
    console.error("--dev refuses to run in production/Vercel environments");
    process.exit(1);
  }
  const { createDevOidcIssuer, DEV_OIDC_AUDIENCE, DEV_OIDC_SUBJECTS } =
    await import("../src/dev-oidc");
  const issuer = await createDevOidcIssuer();
  out.push(
    "",
    "# ── local development only (never set on Vercel) ──",
    "# One shared dev issuer: every dev server mints with the private JWK and verifies with the JWKS.",
    `DEV_OIDC_ISSUER=${quote(issuer.issuer)}`,
    `DEV_OIDC_AUD=${quote(DEV_OIDC_AUDIENCE)}`,
    `DEV_APP_SUB=${quote(DEV_OIDC_SUBJECTS.app)}`,
    `DEV_VIEW_SUB=${quote(DEV_OIDC_SUBJECTS.view)}`,
    `DEV_KEYS_SUB=${quote(DEV_OIDC_SUBJECTS.keys)}`,
    `DEV_OIDC_PRIVATE_JWK=${quote(JSON.stringify(issuer.privateJwk))}`,
    `DEV_OIDC_JWKS=${quote(JSON.stringify(issuer.jwks))}`,
  );
}

process.stdout.write(`${out.join("\n")}\n`);
