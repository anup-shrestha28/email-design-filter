/**
 * Keyword patterns for the rule cascade (DESIGN.md §7.3) and security detection (§7.4).
 * Latin phrases use Unicode-aware word boundaries; CJK phrases have none. Every fragment is a
 * bounded alternation; all matching runs on NFKC-lower-cased text.
 */
import { phraseRegex } from "../util/text";

function both(latin: readonly string[], cjk: readonly string[]): RegExp[] {
  const out = [phraseRegex(latin)];
  if (cjk.length > 0) out.push(phraseRegex(cjk, { boundary: false }));
  return out;
}

/** True when any of the regexes matches. */
export function hit(res: readonly RegExp[], s: string): boolean {
  for (const re of res) if (re.test(s)) return true;
  return false;
}

/** Index of the first match across regexes, or -1. */
export function firstIndex(res: readonly RegExp[], s: string): number {
  let best = -1;
  for (const re of res) {
    const m = re.exec(s);
    if (m && (best < 0 || m.index < best)) best = m.index;
  }
  return best;
}

